"""Produce PLACEHOLDER ridge / SNN / shuffle result files so the figure
pipeline can be exercised end-to-end before every model has been trained
against real MC_RTT data.

Every output JSON carries `"_placeholder": true` and every row's `notes`
field is marked accordingly. The partner's real runs simply overwrite
these files with the same canonical schema and the figure script
produces the publication figures unchanged.

Outputs:
  results/ridge/ridge_results.json
  results/ridge/predictions_f0.25_seed0.npz
  results/snn/snn_results.json
  results/snn/predictions_f0.25_seed0.npz
  results/controls/shuffle_results.json
  results/controls/predictions_f0.25_seed0.npz

Run from the repo root: `python scripts/_generate_placeholder_partner_results.py`
"""
from __future__ import annotations

import json
import logging
import sys
from pathlib import Path

import numpy as np

LOG_FORMAT = "%(asctime)s [%(levelname)s] %(name)s: %(message)s"
logger = logging.getLogger("placeholder_results")

# Proposal-aligned qualitative shape:
#   * ridge best at f=1, degrades fastest as f shrinks
#   * snn competitive at full budget, holds R^2 as f shrinks
#   * shuffle worse than snn at every budget, gap widens at low f
# Numbers are illustrative only and clearly labeled as placeholder.
QUALITATIVE_CURVES: dict[str, dict[float, float]] = {
    "ridge":       {1.00: 0.55, 0.50: 0.48, 0.25: 0.40, 0.10: 0.28},
    "snn":         {1.00: 0.52, 0.50: 0.49, 0.25: 0.47, 0.10: 0.43},
    "snn_shuffle": {1.00: 0.50, 0.50: 0.45, 0.25: 0.38, 0.10: 0.30},
}

SEEDS = (0, 1, 2)
SEED_NOISE_STD = 0.012  # tiny across-seed variability

# Per-model dirs and file names (matches scripts/generate_final_figures.py)
OUT_PATHS: dict[str, dict[str, Path]] = {
    "ridge": {
        "json": Path("results/ridge/ridge_results.json"),
        "pred": Path("results/ridge/predictions_f0.25_seed0.npz"),
    },
    "snn": {
        "json": Path("results/snn/snn_results.json"),
        "pred": Path("results/snn/predictions_f0.25_seed0.npz"),
    },
    "snn_shuffle": {
        "json": Path("results/controls/shuffle_results.json"),
        "pred": Path("results/controls/predictions_f0.25_seed0.npz"),
    },
}

# Knobs for synthetic prediction npz
TRAJECTORY_BINS = 200          # ~10 s of test set at 50 ms bins
BIN_SIZE_MS = 50
SPEED_SCALE = 8.0              # arbitrary units/s; only the shape matters


def _build_tracking_json(model: str, rng: np.random.Generator) -> dict:
    rows: list[dict] = []
    for f, base in QUALITATIVE_CURVES[model].items():
        for seed in SEEDS:
            r2_joint = float(base + rng.normal(0.0, SEED_NOISE_STD))
            r2_vx = float(r2_joint + rng.normal(0.0, 0.01))
            r2_vy = float(r2_joint - rng.normal(0.0, 0.01))
            row = {
                "model": model,
                "event_budget": float(f),
                "seed": int(seed),
                "r2_vx": r2_vx,
                "r2_vy": r2_vy,
                "r2_joint": r2_joint,
                "n_events_used": int(120_000 * f),
                "n_events_total": 120_000,
                "notes": "PLACEHOLDER — replace with real run output",
            }
            if model == "ridge":
                row["best_alpha"] = float(10.0 ** rng.integers(-2, 3))
            rows.append(row)
    blob = {
        "model": model,
        "metric": "velocity_r2",
        "dataset": "NLB_MC_RTT",
        "config": {
            "event_budgets": list(QUALITATIVE_CURVES[model].keys()),
            "seeds": list(SEEDS),
            "_placeholder": True,
        },
        "results": rows,
        "_placeholder": True,
        "_placeholder_note": (
            "synthetic illustrative results generated by "
            "scripts/_generate_placeholder_partner_results.py — overwrite this "
            "file with real run output to refresh the published figures."
        ),
    }
    return blob


def _build_trajectory_npz(model: str, rng: np.random.Generator) -> dict:
    """Synthetic true / predicted velocity over a smooth random-walk window."""
    t = np.arange(TRAJECTORY_BINS)
    # Smooth true trajectory: low-frequency sinusoids + random walk
    walk = np.cumsum(rng.normal(0.0, 0.6, size=(TRAJECTORY_BINS, 2)), axis=0) * 0.05
    base = np.stack(
        [
            SPEED_SCALE * np.sin(2 * np.pi * t / 60.0),
            SPEED_SCALE * np.cos(2 * np.pi * t / 75.0),
        ],
        axis=1,
    )
    y_true = (base + walk).astype(np.float32)
    y_true -= y_true.mean(axis=0, keepdims=True)

    # Noise scale calibrated to the model's f=0.25 R^2
    r2 = QUALITATIVE_CURVES[model][0.25]
    var_true = float(y_true.var())
    # R^2 ≈ 1 - var(noise) / var(true) -> noise_std = sqrt((1-R^2) * var_true)
    noise_std = float(np.sqrt(max(1.0 - r2, 0.0) * var_true))
    y_pred = (y_true + rng.normal(0.0, noise_std, size=y_true.shape)).astype(np.float32)

    return {
        "y_true": y_true,
        "y_pred": y_pred,
        "bin_size_ms": np.array(BIN_SIZE_MS),
        "event_budget": np.array(0.25),
        "model": np.array(model),
        "_placeholder": np.array(True),
    }


def main() -> int:
    logging.basicConfig(level=logging.INFO, format=LOG_FORMAT, stream=sys.stdout)
    rng = np.random.default_rng(20260522)

    for model, paths in OUT_PATHS.items():
        blob = _build_tracking_json(model, rng)
        paths["json"].parent.mkdir(parents=True, exist_ok=True)
        with paths["json"].open("w") as f:
            json.dump(blob, f, indent=2)
        logger.info("wrote %s (%d rows, placeholder)", paths["json"], len(blob["results"]))

        npz_payload = _build_trajectory_npz(model, rng)
        paths["pred"].parent.mkdir(parents=True, exist_ok=True)
        np.savez(paths["pred"], **npz_payload)
        logger.info("wrote %s (placeholder predictions, f=0.25)", paths["pred"])

    # A sibling README so anyone browsing the repo sees the disclaimer fast.
    notice = (
        "# Placeholder result files\n\n"
        "The JSON and NPZ files in `results/ridge/`, `results/snn/`, and\n"
        "`results/controls/` were generated by\n"
        "`scripts/_generate_placeholder_partner_results.py` so the figure\n"
        "pipeline can be exercised end-to-end before every model has been\n"
        "trained on real MC_RTT data.\n\n"
        "Every JSON contains `\"_placeholder\": true` and every row's\n"
        "`notes` field is marked. Real training runs simply overwrite\n"
        "these files using the same canonical schema (see\n"
        "`docs/data_interface.md`) and `scripts/generate_final_figures.py`\n"
        "produces the publication figures unchanged.\n"
    )
    notice_path = Path("results/README.md")
    notice_path.write_text(notice)
    logger.info("wrote %s", notice_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
